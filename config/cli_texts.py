"""Other people's texts in the commands' help, as their code writes them: argparse's, and Django's (Django REST
framework's too), which cli_help.py looks up in the catalog where they're shown. Listed here for the catalog
(`python scripts/i18n.py extract`); only the tests import it.

They are those of the Python and Django HFile is built with (README: Python 3.12, Django 6.1). After an upgrade,
config/tests.py names each one the help shows that isn't here, and each one here it no longer shows: copy it
as their code writes it, then translate it. A placeholder is the name of an option's value in the help (OUTPUT,
which argparse makes of --output); a group, an app's name in the list of commands (`hfile help`).
"""

